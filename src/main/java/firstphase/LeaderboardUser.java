package firstphase;

public class LeaderboardUser {
    private int rank, level, completedMissions, totalXp;
    private String username;
    public int getRank(){return rank;} public void setRank(int v){rank=v;}
    public int getLevel(){return level;} public void setLevel(int v){level=v;}
    public int getCompletedMissions(){return completedMissions;} public void setCompletedMissions(int v){completedMissions=v;}
    public int getTotalXp(){return totalXp;} public void setTotalXp(int v){totalXp=v;}
    public String getUsername(){return username;} public void setUsername(String v){username=v;}
}
